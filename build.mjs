/**
 * Build the dsh-live-tavern browser half.
 *
 * The DSH client module table loads one classic script per plugin and hands it
 * a `require` backed by the shared module table, so the artifact is the
 * esbuild CommonJS output wrapped in `__ModuleLoader__.load`. PixiJS and the
 * Live2D engine are inlined; every other runtime import must stay external
 * because a second copy of a host module breaks the page.
 */

import { build } from 'esbuild'
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = here
const outFile = join(packageRoot, 'lib', 'client.js')
const coreSource = join(here, 'assets', 'vendor', 'live2dcubismcore.min.js')
const coreTarget = join(packageRoot, 'assets', 'vendor', 'live2dcubismcore.min.js')

const result = await build({
  entryPoints: [join(here, 'src', 'client.js')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2020'],
  minify: false,
  legalComments: 'none',
  external: ['react', 'react-dom', 'react-dom/client'],
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'info',
})

const bundled = result.outputFiles[0].text
const core = await readFile(coreSource, 'utf8')

// The Cubism runtime is a classic script that publishes `Live2DCubismCore` as a
// global and must exist before the engine module evaluates. Prepending it to the
// artifact makes that ordering a property of the file instead of the page: no
// index injection, no MIME negotiation, no script-ordering race.
const artifact = `/* dsh-live-tavern browser half — generated by dsh-live-tavern-dev/build.mjs; do not edit. */
/* Live2D Cubism Core — (C) Live2D Inc.; redistributable code under the Live2D Proprietary Software License Agreement. */
${core}
window.__ModuleLoader__.load({
  id: 'dsh-live-tavern-lite',
  factory(require) {
    var module = { exports: {} }
    var exports = module.exports
${bundled}
    return module.exports
  },
})
`

await mkdir(dirname(outFile), { recursive: true })
await writeFile(outFile, artifact, 'utf8')
await mkdir(dirname(coreTarget), { recursive: true })
await copyFile(coreSource, coreTarget)

const bytes = Buffer.byteLength(artifact)
const coreBytes = (await readFile(coreTarget)).length
console.log(`client.js  ${(bytes / 1024).toFixed(0)} KiB  ->  ${outFile}`)
console.log(`cubism    ${(coreBytes / 1024).toFixed(0)} KiB  ->  ${coreTarget}`)
